  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  PROFISSIONAL_CPF text NOT NULL UNIQUE,
  PROFISSIONAL_NOME text NOT NULL,
  PROFISSIONAL_NOME_SOCIAL text,
  PROFISSIONAL_DT_NASCIMENTO date NOT NULL,
  PROFISSIONAL_SEXO text NOT NULL,
  PROFISSIONAL_GENERO text,
  PROFISSIONAL_RACA_COR text NOT NULL,
  PROFISSIONAL_QUILOMBOLA text NOT NULL,
  PROFISSIONAL_NACIONALIDADE text NOT NULL,
  PROFISSIONAL_TELEFONE text,
  PROFISSIONAL_E_MAIL text,
  CO_NIVEL_ESCOLARIDADE text NOT NULL,
  CO_TIPO_ENSINO_MEDIO text NOT NULL,
  NATUREZA_INSTITUICAO_MEDIO_PROFISSIONAL text NOT NULL,
  PROFISSIONAL_CO_UF_RES text NOT NULL,
  PROFISSIONAL_CO_MUNICIPIO_RES text NOT NULL,
  PROFISSIONAL_DS_LOGRADOURO_RES text,
  PROFISSIONAL_NU_ENDERECO_RES text,
  PROFISSIONAL_BAIRRO_RES text,
  PROFISSIONAL_CEP_RES text,
  PROFISSIONAL_LOCALIZACAO_GEOGRAFICA text,
  PROFISSIONAL_LOCALIZACAO_DIFERENCIADA text,
  PROFISSIONAL_DEFICIENCIA text NOT NULL,
  CO_TIPO_FORMACAO_ACADEMICA text NOT NULL,
  CO_AREA_CONHECIMENTO_FORMACAO_ACADEMICA text NOT NULL,
  NO_INSTITUICAO_ENSINO_FORMACAO_ACADEMICA text,
  NATUREZA_INSTITUICAO_SUPERIOR_PROFISSIONAL text,
  ANO_INICIO_FORMACAO_ACADEMICA integer,
  ANO_CONCLUSAO_FORMACAO_ACADEMICA integer NOT NULL,
  CO_ENTIDADE text NOT NULL,
  CO_TIPO_VINCULO text NOT NULL,
  SITUACAO_VINCULO_PROFISSIONAL_REDE text NOT NULL,
  DATA_INICIO_VINCULO_PROFISSIONAL_REDE date NOT NULL,
  DATA_FIM_VINCULO_PROFISSIONAL_REDE date,
  CO_FUNCAO text NOT NULL,
  DATA_INGRESSO date NOT NULL,
  DATA_FIM date,
  CARGA_HORARIA_SEMANAL integer,
  PROFISSIONAL_IDENTIFICACAO_INSTITUICAO text,
  criado_em timestamp DEFAULT now()
);

-- Enable Row Level Security
ALTER TABLE public.profissionais ENABLE ROW LEVEL SECURITY;

CREATE POLICY "profissionais_select" ON public.profissionais FOR SELECT USING (true);
CREATE POLICY "profissionais_insert" ON public.profissionais FOR INSERT WITH CHECK (true);
CREATE POLICY "profissionais_update" ON public.profissionais FOR UPDATE USING (true) WITH CHECK (true);

